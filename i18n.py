class Lang:
    """Тривиальный переводчик с фолбэком на английский."""

    def __init__(self, code: str | None = None):
        self.code = code if code in STRINGS else DEFAULT

    def __call__(self, key: str, **kwargs) -> str:
        template = STRINGS[self.code].get(key) or STRINGS[DEFAULT].get(key, key)
        try:
            return template.format(**kwargs)
        except (KeyError, IndexError):
            return template

    def switch(self, code: str) -> bool:
        if code in STRINGS:
            self.code = code
            return True
        return False
